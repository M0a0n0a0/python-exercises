num1=float(input('enter a number: '))
num2=float(input('enter anumber '))
operation=input('choose operation(+, - , *, /): ')
if operation== '+' :
    result= num1 + num2
    print(result)
elif operation== '*' :
    result= num1 * num2
    print(result)
elif operation== '-' :
    result= num1 - num2
    print(result)
elif operation== '/' :
    result= num1 / num2
    print(result)